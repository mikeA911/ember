// Regenerates the two convenience files next to supabase/migrations/ -- run
// after adding a migration (npm run db:build-sql):
//
//   supabase/combined_migration.sql      every migration concatenated in apply
//                                        order inside one transaction, for a
//                                        fresh project's SQL Editor
//   supabase/migration_status_check.sql  read-only query reporting, per
//                                        migration, whether the tables, columns,
//                                        functions, policies, triggers and
//                                        indexes it creates exist
//   supabase/migration_status_check_recent.sql
//                                        the same check for only the last 10
//                                        migrations -- small enough to paste
//                                        into the SQL Editor after applying a
//                                        few new files
//
// The status check replays the migrations in order (following drops and
// renames) so each object is checked under its final name.
import fs from 'node:fs'
import path from 'node:path'

const dir = path.join(process.cwd(), 'supabase', 'migrations')
const combinedOut = path.join(process.cwd(), 'supabase', 'combined_migration.sql')
const statusOut = path.join(process.cwd(), 'supabase', 'migration_status_check.sql')
const files = fs.readdirSync(dir).filter((f) => f.endsWith('.sql')).sort()

const combined = [
  '-- GENERATED by scripts/build-migration-sql.mjs (npm run db:build-sql) -- do not edit.',
  `-- All ${files.length} supabase/migrations/*.sql files concatenated in apply order, for`,
  '-- pasting into the Supabase SQL Editor on a FRESH project in one shot.',
  '-- The individual files in supabase/migrations/ are the source of truth.',
  '--',
  '-- Runs as ONE transaction: if any statement fails, everything rolls back and',
  '-- the project is left as it was. Only for an EMPTY project -- several files',
  '-- use plain `create policy` / `create trigger`, which fail if re-run.',
  '-- Afterwards, run supabase/migration_status_check.sql to confirm.',
  '',
  'begin;',
  ...files.map((f) => `\n-- ==== supabase/migrations/${f} ====\n${fs.readFileSync(path.join(dir, f), 'utf-8').trimEnd()}\n`),
  '',
  'commit;',
  '',
].join('\n')
fs.writeFileSync(combinedOut, combined)

const ident = (s) => {
  s = s.trim()
  return s.startsWith('"') ? s.slice(1, -1) : s.toLowerCase()
}
const qname = (s) => {
  // schema-qualified name -> [schema, name]
  const parts = s.match(/("[^"]+"|[A-Za-z_][\w$]*)/g).map(ident)
  return parts.length > 1 ? [parts[0], parts[1]] : ['public', parts[0]]
}
const ID = String.raw`(?:"[^"]+"|[A-Za-z_][\w$]*)`
const QID = String.raw`${ID}(?:\s*\.\s*${ID})?`

// Final-state object map: key -> { migration, kind, schema, table, name }
const objects = new Map()
const key = (kind, schema, table, name) => `${kind}|${schema}|${table ?? ''}|${name}`
const add = (m, kind, schema, table, name) => {
  const k = key(kind, schema, table, name)
  if (!objects.has(k)) objects.set(k, { migration: m, kind, schema, table, name })
}
const del = (kind, schema, table, name) => objects.delete(key(kind, schema, table, name))
const rekey = (pred, fn) => {
  for (const [k, o] of [...objects]) {
    if (pred(o)) {
      objects.delete(k)
      fn(o)
      objects.set(key(o.kind, o.schema, o.table, o.name), o)
    }
  }
}

const unparsed = []
for (const file of files) {
  const m = file.replace(/\.sql$/, '')
  let sql = fs.readFileSync(path.join(dir, file), 'utf-8')
  // One left-to-right pass so an apostrophe inside a comment isn't read as a
  // string opener (and vice versa): blank out comments, string literals and
  // dollar-quoted bodies, whichever starts first.
  sql = sql.replace(
    /--[^\n]*|\/\*[\s\S]*?\*\/|\$([A-Za-z_]*)\$[\s\S]*?\$\1\$|'(?:[^']|'')*'/g,
    (t) => (t.startsWith('--') || t.startsWith('/*') ? ' ' : "''"),
  )
  for (let st of sql.split(';')) {
    st = st.replace(/\s+/g, ' ').trim()
    if (!st) continue
    let r
    if ((r = st.match(new RegExp(`^create extension (?:if not exists )?(${ID})`, 'i')))) {
      add(m, 'extension', '', null, ident(r[1]))
    } else if ((r = st.match(new RegExp(`^create table (?:if not exists )?(${QID})`, 'i')))) {
      const [s, t] = qname(r[1])
      add(m, 'table', s, null, t)
    } else if ((r = st.match(new RegExp(`^create (?:or replace )?(?:materialized )?view (?:if not exists )?(${QID})`, 'i')))) {
      const [s, v] = qname(r[1])
      add(m, 'view', s, null, v)
    } else if ((r = st.match(new RegExp(`^create (?:or replace )?function (${QID})`, 'i')))) {
      const [s, f] = qname(r[1])
      add(m, 'function', s, null, f)
    } else if ((r = st.match(new RegExp(`^create policy (${ID}) on (${QID})`, 'i')))) {
      const [s, t] = qname(r[2])
      add(m, 'policy', s, t, ident(r[1]))
    } else if ((r = st.match(new RegExp(`^create (?:or replace )?trigger (${ID}) .*? on (${QID})`, 'i')))) {
      const [s, t] = qname(r[2])
      add(m, 'trigger', s, t, ident(r[1]))
    } else if ((r = st.match(new RegExp(`^create (?:unique )?index (?:concurrently )?(?:if not exists )?(${ID}) on (?:only )?(${QID})`, 'i')))) {
      const [s] = qname(r[2])
      add(m, 'index', s, null, ident(r[1]))
    } else if ((r = st.match(new RegExp(`^drop table (?:if exists )?(${QID})`, 'i')))) {
      const [s, t] = qname(r[1])
      del('table', s, null, t)
      rekey((o) => o.schema === s && o.table === t, (o) => { o.kind = 'dropped' })
    } else if ((r = st.match(new RegExp(`^drop function (?:if exists )?(${QID})`, 'i')))) {
      const [s, f] = qname(r[1])
      del('function', s, null, f)
    } else if ((r = st.match(new RegExp(`^drop policy (?:if exists )?(${ID}) on (${QID})`, 'i')))) {
      const [s, t] = qname(r[2])
      del('policy', s, t, ident(r[1]))
    } else if ((r = st.match(new RegExp(`^drop trigger (?:if exists )?(${ID}) on (${QID})`, 'i')))) {
      const [s, t] = qname(r[2])
      del('trigger', s, t, ident(r[1]))
    } else if ((r = st.match(new RegExp(`^drop index (?:if exists )?(${QID})`, 'i')))) {
      const [s, i] = qname(r[1])
      del('index', s, null, i)
    } else if ((r = st.match(new RegExp(`^alter table (?:if exists )?(?:only )?(${QID}) rename to (${ID})$`, 'i')))) {
      const [s, from] = qname(r[1])
      const to = ident(r[2])
      rekey((o) => o.kind === 'table' && o.schema === s && o.name === from, (o) => { o.name = to })
      rekey((o) => o.schema === s && o.table === from, (o) => { o.table = to })
    } else if ((r = st.match(new RegExp(`^alter table (?:if exists )?(?:only )?(${QID}) rename column (${ID}) to (${ID})$`, 'i')))) {
      const [s, t] = qname(r[1])
      const from = ident(r[2]), to = ident(r[3])
      rekey((o) => o.kind === 'column' && o.schema === s && o.table === t && o.name === from, (o) => { o.name = to })
    } else if ((r = st.match(new RegExp(`^alter index (?:if exists )?(${QID}) rename to (${ID})$`, 'i')))) {
      const [s, from] = qname(r[1])
      const to = ident(r[2])
      if (!objects.has(key('index', s, null, from))) add(m, 'index', s, null, to) // implicit (pkey/unique) index
      rekey((o) => o.kind === 'index' && o.schema === s && o.name === from, (o) => { o.name = to })
    } else if ((r = st.match(new RegExp(`^alter trigger (${ID}) on (${QID}) rename to (${ID})$`, 'i')))) {
      const [s, t] = qname(r[2])
      const from = ident(r[1]), to = ident(r[3])
      rekey((o) => o.kind === 'trigger' && o.schema === s && o.table === t && o.name === from, (o) => { o.name = to })
    } else if ((r = st.match(new RegExp(`^alter policy (${ID}) on (${QID}) rename to (${ID})$`, 'i')))) {
      const [s, t] = qname(r[2])
      const from = ident(r[1]), to = ident(r[3])
      rekey((o) => o.kind === 'policy' && o.schema === s && o.table === t && o.name === from, (o) => { o.name = to })
    } else if ((r = st.match(new RegExp(`^alter table (?:if exists )?(?:only )?(${QID}) (.*)$`, 'i')))) {
      const [s, t] = qname(r[1])
      // May hold several comma-separated actions; column types can contain
      // commas only inside parens, so split on top-level commas.
      const actions = []
      let depth = 0, cur = ''
      for (const ch of r[2]) {
        if (ch === '(') depth++
        if (ch === ')') depth--
        if (ch === ',' && depth === 0) { actions.push(cur); cur = '' } else cur += ch
      }
      actions.push(cur)
      for (const a of actions.map((x) => x.trim())) {
        let c
        if ((c = a.match(new RegExp(`^add column (?:if not exists )?(${ID})`, 'i')))) add(m, 'column', s, t, ident(c[1]))
        else if ((c = a.match(new RegExp(`^drop column (?:if exists )?(${ID})`, 'i')))) del('column', s, t, ident(c[1]))
      }
    } else if (/^(create|drop|alter)\b/i.test(st) && !/^alter (table|policy|function|default privileges)\b/i.test(st)) {
      unparsed.push(`${file}: ${st.slice(0, 100)}`)
    }
  }
}

const allExpected = [...objects.values()].filter((o) => o.kind !== 'dropped')
const lit = (v) => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`)
// One status query over a run of migration files (ord = position in the
// full apply order). The full file covers every migration; the recent one
// only the last RECENT_COUNT, so it stays small enough for the SQL Editor.
function statusQuery(subset, firstOrd, scope) {
const names = new Set(subset.map((f) => f.replace(/\.sql$/, '')))
const expected = allExpected.filter((o) => names.has(o.migration))
const migrationRows = subset.map((f, i) => `    (${firstOrd + i}, ${lit(f.replace(/\.sql$/, ''))})`).join(',\n')
const objectRows = expected
  .map((o) => `    (${lit(o.migration)}, ${lit(o.kind)}, ${lit(o.schema)}, ${lit(o.table)}, ${lit(o.name)})`)
  .join(',\n')

return `-- GENERATED by scripts/build-migration-sql.mjs (npm run db:build-sql) -- do not edit.
-- Migration status check -- READ-ONLY, changes nothing.
-- Covers ${scope} (${subset.length} files, ${expected.length} schema objects).
--
-- Run in the Supabase SQL Editor of the project you want to inspect.
-- One row per migration file, in apply order:
--   applied      every table/column/function/policy/trigger/index it creates exists
--   PARTIAL      some exist -- inspect "missing" before re-running anything
--   NOT APPLIED  none exist
--   unverifiable the file only changes data, grants or existing definitions
--
-- Limits: it checks that objects exist by name, not that their definitions
-- match. A migration that only redefines an existing function or policy, or
-- only inserts/updates rows, shows as "unverifiable". Objects a later
-- migration drops or renames are checked under their final name.

with migrations(ord, migration) as (
  values
${migrationRows}
),
expected(migration, kind, schema_name, table_name, object_name) as (
  values
${objectRows}
),
checked as (
  select e.*,
    case e.kind
      when 'extension' then exists (select 1 from pg_extension x where x.extname = e.object_name)
      when 'table' then exists (select 1 from pg_class c join pg_namespace n on n.oid = c.relnamespace
                                where n.nspname = e.schema_name and c.relname = e.object_name and c.relkind in ('r', 'p', 'v', 'm'))
      when 'view' then exists (select 1 from pg_class c join pg_namespace n on n.oid = c.relnamespace
                               where n.nspname = e.schema_name and c.relname = e.object_name and c.relkind in ('v', 'm'))
      when 'column' then exists (select 1 from information_schema.columns ic
                                 where ic.table_schema = e.schema_name and ic.table_name = e.table_name and ic.column_name = e.object_name)
      when 'function' then exists (select 1 from pg_proc p join pg_namespace n on n.oid = p.pronamespace
                                   where n.nspname = e.schema_name and p.proname = e.object_name)
      when 'policy' then exists (select 1 from pg_policies pp
                                 where pp.schemaname = e.schema_name and pp.tablename = e.table_name and pp.policyname = e.object_name)
      when 'trigger' then exists (select 1 from pg_trigger t join pg_class c on c.oid = t.tgrelid join pg_namespace n on n.oid = c.relnamespace
                                  where not t.tgisinternal and n.nspname = e.schema_name and c.relname = e.table_name and t.tgname = e.object_name)
      when 'index' then exists (select 1 from pg_indexes i where i.schemaname = e.schema_name and i.indexname = e.object_name)
    end as present
  from expected e
)
select
  m.ord,
  m.migration,
  case
    when count(c.kind) = 0 then 'unverifiable'
    when bool_and(c.present) then 'applied'
    when bool_or(c.present) then 'PARTIAL'
    else 'NOT APPLIED'
  end as status,
  count(c.kind) filter (where c.present) as found,
  count(c.kind) as expected,
  string_agg(c.kind || ' ' || coalesce(c.table_name || '.', '') || c.object_name, ', ' order by c.kind, c.object_name)
    filter (where not c.present) as missing
from migrations m
left join checked c on c.migration = m.migration
group by m.ord, m.migration
order by m.ord;
`
}

const RECENT_COUNT = 10
const recentOut = path.join(process.cwd(), 'supabase', 'migration_status_check_recent.sql')
fs.writeFileSync(statusOut, statusQuery(files, 1, 'every file in supabase/migrations/'))
fs.writeFileSync(
  recentOut,
  statusQuery(files.slice(-RECENT_COUNT), Math.max(files.length - RECENT_COUNT, 0) + 1, `the last ${RECENT_COUNT} files in supabase/migrations/`)
)

console.log(`Wrote supabase/combined_migration.sql (${files.length} migrations)`)
console.log(`Wrote supabase/migration_status_check.sql (${allExpected.length} schema objects)`)
console.log(`Wrote supabase/migration_status_check_recent.sql (last ${Math.min(RECENT_COUNT, files.length)} migrations)`)
if (unparsed.length > 0) {
  // A create/alter/drop the replay doesn't understand could hide a renamed or
  // dropped object and make the status check report a false gap.
  console.error(`\n${unparsed.length} statement(s) not understood -- extend the parser:`)
  for (const u of unparsed) console.error('  ' + u)
  process.exit(1)
}
